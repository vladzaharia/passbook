import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { describe, expect, it } from 'vitest';
import { WALLET_CAPABILITIES } from '../src/generated/wallet-capabilities.ts';
import { columns, renderDoc, renderModule } from './lib/wallet-capabilities.ts';

const root = join(import.meta.dirname, '..');
const HEADER = '// Generated by tools/gen-wallet-capabilities.ts. Do not edit.\n';

describe('wallet capability matrix', () => {
  it('is stable', () => {
    expect(renderModule(HEADER)).toBe(renderModule(HEADER));
    expect(renderDoc()).toBe(renderDoc());
  });

  it('matches the committed files (run npm run gen)', () => {
    expect(readFileSync(join(root, 'src/generated/wallet-capabilities.ts'), 'utf8')).toBe(
      renderModule(HEADER),
    );
    expect(readFileSync(join(root, 'docs/design/wallet-providers/capabilities.md'), 'utf8')).toBe(
      renderDoc(),
    );
  });

  it('equals what the compilers declare', () => {
    for (const c of columns()) {
      expect((WALLET_CAPABILITIES[c.target] as Record<string, unknown>)[c.type]).toEqual(c.table);
    }
  });
});
