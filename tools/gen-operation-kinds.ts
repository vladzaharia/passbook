// Writes src/generated/operation-kinds.ts (every kind in src/shared/operations/kinds/*.ts) and
// src/worker/generated/operation-runners.ts (every module's hooks in src/worker/modules/*/operations.ts).
// The runners are Worker code, so they stay out of src/generated, which the web typecheck reads.
// Run via `npm run gen`; CI fails if the output drifts.
import { existsSync, mkdirSync, readdirSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const root = resolve(import.meta.dirname, '..');
const HEADER = '// Generated by tools/gen-operation-kinds.ts. Do not edit; run `npm run gen`.\n';
const sorted = (names: string[]) => names.sort((a, b) => (a < b ? -1 : a > b ? 1 : 0));

const kindFiles = sorted(
  readdirSync(resolve(root, 'src/shared/operations/kinds')).filter(
    (f) => f.endsWith('.ts') && !f.endsWith('.test.ts'),
  ),
);
const kinds = [
  HEADER,
  "import type { OperationKindDef } from '../shared/operations/define.ts';",
  ...kindFiles.map((f, i) => `import * as k${i} from '../shared/operations/kinds/${f}';`),
  '',
  '/** Every declared operation kind. */',
  `export const OPERATION_KINDS: readonly OperationKindDef[] = [${kindFiles
    .map((_, i) => `...(Object.values(k${i}) as OperationKindDef[])`)
    .join(', ')}];`,
  '',
].join('\n');

const modulesDir = resolve(root, 'src/worker/modules');
const owners = sorted(
  readdirSync(modulesDir, { withFileTypes: true })
    .filter((e) => e.isDirectory() && existsSync(resolve(modulesDir, e.name, 'operations.ts')))
    .map((e) => e.name),
);
const runners = [
  HEADER,
  '// biome-ignore-all format: generated',
  '// biome-ignore-all assist/source/organizeImports: generated',
  '// biome-ignore-all lint: generated',
  "import type { OperationRunners } from '../modules/operations/registry.ts';",
  ...owners.map(
    (m, i) => `import { operationRunners as r${i} } from '../modules/${m}/operations.ts';`,
  ),
  '',
  '/** Run, retry and cancel hooks by kind. */',
  `export const OPERATION_RUNNERS: OperationRunners = { ${owners.map((_, i) => `...r${i}`).join(', ')} };`,
  '',
].join('\n');

writeFileSync(resolve(root, 'src/generated/operation-kinds.ts'), kinds);
mkdirSync(resolve(root, 'src/worker/generated'), { recursive: true });
writeFileSync(resolve(root, 'src/worker/generated/operation-runners.ts'), runners);
