// Part of `npm run gen`: the SSR pages share the SPA kit's source, compiled for static pages.
// - src/generated/ssr-controls.css: the classes of Button (primary, outline), Input, Label and the
//   danger Callout, applied through Tailwind to the SSR markup's .btn, input, label and .callout.
// - public/pass-tilt.js: the pass stage's pointer tilt (src/web/pass-card/tilt.ts) for /p.
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { compile, optimize } from '@tailwindcss/node';
import { createElement, type ReactElement } from 'react';
import { renderToStaticMarkup } from 'react-dom/server';
import { build, type Plugin, runnerImport } from 'vite';
import { parseCss } from './lib/css-tokens.ts';
import { CONTROL_SOURCES, sourceHash, TILT_SOURCE } from './lib/ssr-kit.ts';

const root = resolve(import.meta.dirname, '..');

const noCss: Plugin = {
  name: 'no-side-effect-css',
  enforce: 'pre',
  resolveId: (id) => (id.endsWith('.css') ? '\0no-css' : null),
  load: (id) => (id === '\0no-css' ? 'export {}' : null),
};
const load = async <T>(id: string): Promise<T> =>
  (
    await runnerImport<T>(resolve(root, id), {
      configFile: false,
      root,
      logLevel: 'error',
      plugins: [noCss],
    })
  ).module;

type Component = (props: Record<string, unknown>) => ReactElement;
const { buttonVariants } = await load<{
  buttonVariants: (v: { variant: string; size: string }) => string;
}>('src/web/ui/button.tsx');
const { CONTROL, CONTROL_HEIGHT } = await load<{ CONTROL: string; CONTROL_HEIGHT: string }>(
  'src/web/ui/input.tsx',
);
const { Label } = await load<{ Label: Component }>('src/web/ui/label.tsx');
const { Callout } = await load<{ Callout: Component }>('src/web/ui/callout.tsx');

const tokens = (classes: string) => classes.split(/\s+/).filter(Boolean);
const minus = (a: string[], b: string[]) => a.filter((c) => !b.includes(c));
/** The class lists of a component's static markup, in document order (lucide's own dropped). */
const classesOf = (el: ReactElement) =>
  [...renderToStaticMarkup(el).matchAll(/class="([^"]*)"/g)].map((m) =>
    tokens(m[1] ?? '').filter((c) => !c.startsWith('lucide')),
  );

const primary = tokens(buttonVariants({ variant: 'primary', size: 'md' }));
const outline = tokens(buttonVariants({ variant: 'outline', size: 'md' }));
const common = primary.filter((c) => outline.includes(c));
const [label = []] = classesOf(createElement(Label, {}, 'x'));
const [box = [], icon = [], body = [], text = []] = classesOf(
  createElement(Callout, { tone: 'danger' }, 'x'),
);

// Kit utilities (utilities.css) are plain classes there; Tailwind applies them as @utility.
const kit = parseCss(readFileSync(resolve(root, 'src/web/styles/utilities.css'), 'utf8'))
  .map((r) => `@utility ${r.selector.slice(1)}{${r.decls.map(([k, v]) => `${k}:${v}`).join(';')}}`)
  .join('\n');

const rule = (selector: string, classes: string[]) => `${selector}{@apply ${classes.join(' ')};}`;
const input = `@import "tailwindcss/theme" theme(reference);
@reference "@polaris-key/brand/theme.css";
${kit}
${rule('.btn', common)}
${rule('.btn:not(.outline)', minus(primary, common))}
${rule('.btn.outline', minus(outline, common))}
${rule('input:where(:not([type="hidden"],[type="radio"],[type="checkbox"]))', tokens(`${CONTROL} ${CONTROL_HEIGHT}`))}
${rule('label', label)}
${rule('.callout', box)}
${rule('.callout>svg', icon)}
${rule('.callout>span', [...body, ...text])}
`;
const compiler = await compile(input, {
  base: resolve(root, 'src/web/styles'),
  onDependency() {},
});
const css = optimize(compiler.build([]), { minify: true })
  .code.replace(/\/\*![^*]*\*\/\s*/, '')
  .trim();
writeFileSync(
  resolve(root, 'src/generated/ssr-controls.css'),
  `/* Generated by tools/build-ssr-kit.ts from the kit's Button, Input, Label and Callout (sources ${sourceHash(root, CONTROL_SOURCES)}). Do not edit; run \`npm run gen\`. */\n${css}\n`,
);

const ENTRY = 'pass-tilt-entry';
const bundle = await build({
  configFile: false,
  root,
  logLevel: 'error',
  plugins: [
    {
      name: 'pass-tilt-entry',
      resolveId: (id) => (id === ENTRY ? `\0${ENTRY}` : null),
      load: (id) =>
        id === `\0${ENTRY}`
          ? `import { bindTilt } from ${JSON.stringify(resolve(root, TILT_SOURCE))};
const stage = document.querySelector('.pc-stage[data-tilt]');
if (stage) bindTilt(stage);`
          : null,
    },
  ],
  build: {
    write: false,
    minify: true,
    rolldownOptions: { input: ENTRY, output: { format: 'iife' } },
  },
});
const result = (Array.isArray(bundle) ? bundle[0] : bundle) as { output: { code?: string }[] };
const code = result.output[0]?.code?.trim();
if (!code) throw new Error('pass-tilt.js: empty bundle');
writeFileSync(
  resolve(root, 'public/pass-tilt.js'),
  `// Generated by tools/build-ssr-kit.ts from ${TILT_SOURCE} (sources ${sourceHash(root, [TILT_SOURCE])}). Do not edit; run \`npm run gen\`.\n${code}\n`,
);
console.log(`ssr kit: controls ${css.length} bytes, pass-tilt.js ${code.length} bytes`);
