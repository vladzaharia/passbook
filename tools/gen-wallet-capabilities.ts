// Writes src/generated/wallet-capabilities.ts and docs/design/wallet-providers/capabilities.md.
// Run via `npm run gen`; CI fails if the output drifts.
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { renderDoc, renderModule } from './lib/wallet-capabilities.ts';

const root = resolve(import.meta.dirname, '..');
const HEADER = '// Generated by tools/gen-wallet-capabilities.ts. Do not edit.\n';

for (const [file, content] of [
  ['src/generated/wallet-capabilities.ts', renderModule(HEADER)],
  ['docs/design/wallet-providers/capabilities.md', renderDoc()],
] as const) {
  mkdirSync(dirname(join(root, file)), { recursive: true });
  writeFileSync(join(root, file), content);
}
