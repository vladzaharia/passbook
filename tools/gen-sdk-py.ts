// Generates sdk/python/src/passbook/_generated from docs/api/openapi.v1.json and docs/api/sdk-names.json.
// `node tools/gen-sdk-py.ts` writes; `--check` fails when the committed files differ (run in `npm run check:rules`).
import { readFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { snake } from '../src/shared/sdk-names.ts';
import { drift, writeFiles } from './lib/gen-files.ts';
import { newestApiVersion, pyApiVersionFile } from './lib/sdk-api-version.ts';
import { Models } from './lib/sdk-model.ts';
import { modelsFile, planOps, resourcesFile, resourceTree } from './lib/sdk-py-emit.ts';
import { sampleOf } from './lib/sdk-sample.ts';
import { type OpenApiDoc, type SdkNames, sdkOperations } from './lib/sdk-ts-ops.ts';

const root = resolve(import.meta.dirname, '..');
export const OUT = 'sdk/python/src/passbook/_generated';

/** Generated files by path under OUT. */
export function generate(doc: OpenApiDoc, names: SdkNames): Map<string, string> {
  const models = new Models(doc.components.schemas);
  const plan = planOps(models, sdkOperations(doc, names));
  return new Map([
    ['__init__.py', '# Generated by tools/gen-sdk-py.ts. Do not edit.\n'],
    ['api_version.py', pyApiVersionFile(newestApiVersion())],
    ['models.py', modelsFile(models)],
    ['resources.py', resourcesFile(resourceTree(plan))],
  ]);
}

/** A feed says it is done with `hasMore: false`; a page with `nextCursor: null`. */
function endOfList(page: object): object {
  return 'hasMore' in page ? { ...page, hasMore: false } : { ...page, nextCursor: null };
}

const platformOwned = (
  doc: OpenApiDoc,
  op: { http: string; path: string; resource: string[] },
): boolean => {
  const raw = doc.paths[op.path]?.[op.http.toLowerCase()] as
    | { 'x-platform-scope'?: string }
    | undefined;
  return raw?.['x-platform-scope'] !== undefined || op.resource[0] === 'platform';
};

/** One row per operation for tests/test_generated_ops.py: how to call it, and what the server would send. */
export function manifest(doc: OpenApiDoc, names: SdkNames): string {
  const schemas = doc.components.schemas;
  const rows = planOps(new Models(schemas), sdkOperations(doc, names)).map(
    ({ op, path, query }) => {
      const result = op.schemas.result
        ? (sampleOf(schemas, op.schemas.result) as object)
        : undefined;
      const body = op.schemas.body ? sampleOf(schemas, op.schemas.body) : undefined;
      return {
        id: op.id,
        call: [...op.resource.map(snake), snake(op.method)].join('.'),
        // Platform-scoped operations are callable by keys but not published in the portal, so they have no snippet.
        published: !platformOwned(doc, op),
        http: op.http,
        path: op.path,
        pathParams: path.map((p) => ({ name: p.name, py: p.py, integer: p.ty.k === 'int' })),
        query: query
          .filter((q) => q.required)
          .map((q) => ({
            name: q.name,
            py: q.py,
            value: sampleOf(schemas, op.schemas.query.find((x) => x.name === q.name)?.schema ?? {}),
          })),
        ...(body !== undefined ? { body } : {}),
        binary: op.binary !== undefined,
        idempotent: op.idempotent,
        raw: op.raw,
        cursor: op.cursor ?? null,
        // A list's sample ends after one page.
        ...(result ? { result: op.cursor ? endOfList(result) : result } : {}),
      };
    },
  );
  return `${JSON.stringify(rows, null, 1)}\n`;
}

export { drift };

/** Python leaves `__pycache__` beside what we write; it is not ours to remove or to flag. */
export const owns = (p: string): boolean => !p.includes('__pycache__');

function main(): void {
  const read = <T>(file: string): T => JSON.parse(readFileSync(resolve(root, file), 'utf8')) as T;
  const doc = read<OpenApiDoc>('docs/api/openapi.v1.json');
  const names = read<SdkNames>('docs/api/sdk-names.json');
  const files = generate(doc, names);
  files.set('../../../tests/ops.json', manifest(doc, names));
  const dir = resolve(root, OUT);
  if (process.argv.includes('--check')) {
    const bad = drift(files, dir, owns);
    if (bad.length) {
      console.error(`sdk/python is out of date: ${bad.join(', ')}. Run: node tools/gen-sdk-py.ts`);
      process.exit(1);
    }
    return;
  }
  writeFiles(files, dir, owns);
  console.log(`sdk/python: ${files.size} files generated`);
}

if (import.meta.main) main();
