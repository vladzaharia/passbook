const words = (root: string, sources: readonly string[]): string[] => {
  const out = new Set<string>();
  for (const file of sources.filter((f) => f.endsWith('.tsx')))
    for (const word of readFileSync(resolve(root, file), 'utf8').split(/[\s"'`]+/))
      if (word) out.add(word);
  return [...out].sort();
};

/**
 * Tailwind's utilities for those sources, without preflight: the portal has its own base, and the
 * playground island loads this sheet after it.
 */
async function kitCss(
  root: string,
  sources: readonly string[],
  name: string,
  px = false,
): Promise<string> {
  const kit = parseCss(readFileSync(resolve(root, 'src/web/styles/utilities.css'), 'utf8'))
    .map(
      (r) => `@utility ${r.selector.slice(1)}{${r.decls.map(([k, v]) => `${k}:${v}`).join(';')}}`,
    )
    .join('\n');
  const input = `@import "tailwindcss/theme" theme(reference);
@reference "@polaris-key/brand/theme.css";
${kit}
@tailwind utilities;
`;
  const compiler = await compile(input, {
    base: resolve(root, 'src/web/styles'),
    onDependency() {},
  });
  const built = optimize(compiler.build(words(root, sources)), { minify: true })
    .code.replace(/\/\*![^*]*\*\/\s*/, '')
    .trim();
  // The developer site's root font size is 14 px: its bar must not shrink with it, so type, radius
  // and rem become px (the type and radius tokens are rem, resolved from the generated tokens).
  const tokens = new Map(
    [
      ...readFileSync(resolve(root, 'src/generated/ssr-tokens.css'), 'utf8').matchAll(
        /(--pk-(?:font-size|line-height|radius)-[\w-]+):\s*([\d.]+rem|[\d.]+px)/g,
      ),
    ].map((m) => [m[1], m[2]]),
  );
  const css = px
    ? built
        .replace(
          /var\((--pk-(?:font-size|line-height|radius)-[\w-]+)\)/g,
          (all, name) => tokens.get(name) ?? all,
        )
        .replace(
          /(?<![\\.\w])(-?\d*\.?\d+)rem/g,
          (_, n) => `${Number((Number.parseFloat(n) * 16).toFixed(3))}px`,
        )
    : built;
  return `/* Generated by tools/build-playground-kit.ts from the ${name} kit pieces (${sourceHash(root, sources)}). Do not edit; run \`npm run gen\`. */\n${css}\n`;
}

