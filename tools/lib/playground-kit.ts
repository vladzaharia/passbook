import { readFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { compile, optimize } from '@tailwindcss/node';
import { parseCss } from './css-tokens.ts';
import { sourceHash } from './ssr-kit.ts';

/**
 * The kit pieces the developer playground embeds: the channel switcher and panes, the wallet
 * report and the small controls inside them. Their class names are the playground's kit CSS.
 */
export const PLAYGROUND_KIT_SOURCES = [
  'src/web/channel-previews/channel-previews.tsx',
  'src/web/channel-previews/wallet-channel.tsx',
  'src/web/channel-previews/fidelity-notes.tsx',
  'src/web/ui/badge.tsx',
  'src/web/ui/callout.tsx',
  'src/web/ui/empty-state.tsx',
  'src/web/ui/skeleton.tsx',
  'src/web/ui/select.tsx',
  'src/web/styles/utilities.css',
  'node_modules/@polaris-key/brand/css/theme.css',
] as const;

const words = (root: string): string[] => {
  const out = new Set<string>();
  for (const file of PLAYGROUND_KIT_SOURCES.filter((f) => f.endsWith('.tsx')))
    for (const word of readFileSync(resolve(root, file), 'utf8').split(/[\s"'`]+/))
      if (word) out.add(word);
  return [...out].sort();
};

/**
 * Tailwind's utilities for those sources, without preflight: the portal has its own base, and the
 * playground island loads this sheet after it.
 */
export async function playgroundKitCss(root: string): Promise<string> {
  const kit = parseCss(readFileSync(resolve(root, 'src/web/styles/utilities.css'), 'utf8'))
    .map(
      (r) => `@utility ${r.selector.slice(1)}{${r.decls.map(([k, v]) => `${k}:${v}`).join(';')}}`,
    )
    .join('\n');
  const input = `@import "tailwindcss/theme" theme(reference);
@reference "@polaris-key/brand/theme.css";
${kit}
@tailwind utilities;
`;
  const compiler = await compile(input, {
    base: resolve(root, 'src/web/styles'),
    onDependency() {},
  });
  const css = optimize(compiler.build(words(root)), { minify: true })
    .code.replace(/\/\*![^*]*\*\/\s*/, '')
    .trim();
  return `/* Generated by tools/build-playground-kit.ts from the playground's kit pieces (${sourceHash(root, PLAYGROUND_KIT_SOURCES)}). Do not edit; run \`npm run gen\`. */\n${css}\n`;
}
