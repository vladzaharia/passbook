import { readFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { compile, optimize } from '@tailwindcss/node';
import { parseCss } from './css-tokens.ts';
import { sourceHash } from './ssr-kit.ts';

/**
 * The markup /p renders (src/worker/ssr/pass-page.tsx): the portal's HolderPassView and the kit
 * pieces in it. Their class names, with the SPA's theme and kit utilities, are the page's CSS.
 */
export const HOLDER_SOURCES = [
  'src/worker/ssr/pass-page.tsx',
  'src/web/portal/holder-heading.tsx',
  'src/web/portal/holder-pass-view.tsx',
  'src/web/portal/holder-parts.tsx',
  'src/web/portal/holder-qr.tsx',
  'src/web/portal/add/add-block.tsx',
  'src/web/portal/add/added.tsx',
  'src/web/portal/add/ways.tsx',
  'src/web/ui/apple-wallet-badge.tsx',
  'src/web/ui/callout.tsx',
  'src/web/styles/utilities.css',
  'node_modules/@polaris-key/brand/css/theme.css',
] as const;

/** Every whitespace- or quote-separated word of the sources; Tailwind ignores the non-classes. */
export function candidatesOf(root: string): string[] {
  const words = new Set<string>();
  for (const file of HOLDER_SOURCES.filter((f) => f.endsWith('.tsx'))) {
    for (const word of readFileSync(resolve(root, file), 'utf8').split(/[\s"'`]+/))
      if (word) words.add(word);
  }
  return [...words].sort();
}

/**
 * Tailwind's preflight and the utilities the sources name, unlayered: on /p they follow the SSR
 * base sheet (THEME_CSS) and precede the card's own sheets, as the SPA's layers order them.
 */
export async function ssrHolderCss(root: string): Promise<string> {
  // Kit utilities (utilities.css) are plain classes there; Tailwind applies them as @utility.
  const kit = parseCss(readFileSync(resolve(root, 'src/web/styles/utilities.css'), 'utf8'))
    .map(
      (r) => `@utility ${r.selector.slice(1)}{${r.decls.map(([k, v]) => `${k}:${v}`).join(';')}}`,
    )
    .join('\n');
  const input = `@import "tailwindcss/theme" theme(reference);
@reference "@polaris-key/brand/theme.css";
@import "tailwindcss/preflight";
${kit}
@tailwind utilities;
`;
  const compiler = await compile(input, {
    base: resolve(root, 'src/web/styles'),
    onDependency() {},
  });
  const css = optimize(compiler.build(candidatesOf(root)), { minify: true })
    .code.replace(/\/\*![^*]*\*\/\s*/, '')
    .trim();
  return `/* Generated by tools/build-ssr-holder.ts from /p's markup sources (${sourceHash(root, HOLDER_SOURCES)}). Do not edit; run \`npm run gen\`. */\n${css}\n`;
}
