/**
 * The SPA's token sheets as the SSR pages and emails consume them (tools/build-ssr-tokens.ts):
 * the brand's Rubik faces, every custom-property block with its selectors, and the cascade
 * resolved per theme for inline email styles.
 */
import { readFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { parseCss, printCss, type Rule, resolveTheme, tokenRules } from './css-tokens.ts';

/** In cascade order, as app.css imports them. */
export const TOKEN_SOURCES = [
  'node_modules/@polaris-key/brand/css/tokens.css',
  'src/web/styles/wallet.css',
  'src/web/styles/motion.css',
] as const;
export const FONT_SOURCE = 'node_modules/@polaris-key/brand/fonts/fonts.css';
/** Where the SSR @font-face rules point; the generator copies the files there. */
export const FONT_URL = '/fonts/';

export interface Sources {
  tokens: string[];
  fonts: string;
}

export const readSources = (root: string): Sources => ({
  tokens: TOKEN_SOURCES.map((p) => readFileSync(resolve(root, p), 'utf8')),
  fonts: readFileSync(resolve(root, FONT_SOURCE), 'utf8'),
});

/** Brand sections and sub-brands other than the platform's own (data-service, data-brand). */
function foreign(css: string): string[] {
  const names = [...css.matchAll(/\[data-(?:service|brand)="([a-z]+)"\]/g)].map((m) => m[1] ?? '');
  return [...new Set(names)].filter((n) => n !== 'core');
}

/**
 * Every theme-level token rule (on :root or a data-theme/data-service root) in cascade order,
 * without the other sections' palettes. Component-scoped custom properties stay in their sheets.
 */
export function tokenSheet(sources: Sources): Rule[] {
  const other = sources.tokens.flatMap(foreign);
  const keep = (name: string) =>
    !other.some(
      (s) =>
        name.startsWith(`--pk-state-${s}-`) ||
        name === `--pk-service-${s}` ||
        name.startsWith(`--pk-service-${s}-`) ||
        name.startsWith(`--pk-${s}-`),
    );
  const ours = (selector: string) =>
    selector
      .split(',')
      .some((s) => /^(:root|\[data-)/.test(s) && !other.some((o) => s.includes(`="${o}"]`)));
  return sources.tokens
    .flatMap((css) => tokenRules(parseCss(css), keep))
    .filter((r) => ours(r.selector));
}

/** The Rubik faces (latin, latin-ext, the metric-matched fallback) with their files under /fonts/. */
export function fontSheet(sources: Sources): { rules: Rule[]; files: string[] } {
  const files: string[] = [];
  const rules = parseCss(sources.fonts)
    .filter((r) => {
      const family = r.decls.find(([k]) => k === 'font-family')?.[1] ?? '';
      return /^"Rubik( Fallback)?"$/.test(family);
    })
    .map((r) => ({
      ...r,
      decls: r.decls.map(([k, v]): [string, string] => [
        k,
        v.replace(/url\("\.\/([^"]+)"\)/g, (_, file: string) => {
          files.push(file);
          return `url("${FONT_URL}${file}")`;
        }),
      ]),
    }));
  return { rules, files };
}

export const SSR_TOKENS_HEADER = `/* Generated by tools/build-ssr-tokens.ts from @polaris-key/brand fonts.css and tokens.css,
   src/web/styles/wallet.css and motion.css. Do not edit; run \`npm run gen\`. */\n`;

export function ssrTokensCss(sources: Sources): string {
  return `${SSR_TOKENS_HEADER}${printCss([...fontSheet(sources).rules, ...tokenSheet(sources)])}`;
}

const px = (rem: string) => {
  const m = /^(-?[\d.]+)rem$/.exec(rem);
  if (!m) throw new Error(`Expected rem, got ${rem}`);
  return Number(m[1]) * 16;
};

/** Colour roles emails use, by token. */
const EMAIL_COLORS = {
  page: '--pk-surface-page',
  card: '--pk-surface-raised',
  sunken: '--pk-surface-sunken',
  strong: '--pk-text-strong',
  text: '--pk-text-default',
  muted: '--pk-text-muted',
  line: '--pk-border-subtle',
  lineStrong: '--pk-border-strong',
  accent: '--pk-accent',
  accentFg: '--pk-accent-fg',
  accentOn: '--pk-accent-on',
  foil1: '--wl-foil-1',
  foil2: '--wl-foil-2',
  foil3: '--wl-foil-3',
} as const;

export type EmailColors = Record<keyof typeof EMAIL_COLORS, string>;

/** The tokens per theme, as the email shell inlines them (px for sizes). */
export function emailTokens(sources: Sources) {
  const rules = tokenSheet(sources);
  const scheme = (system: 'light' | 'dark') => {
    const t = resolveTheme(rules, { system });
    const colors = {} as EmailColors;
    for (const [role, name] of Object.entries(EMAIL_COLORS)) {
      const value = t.get(name);
      if (!value || !/^#[0-9a-f]{3,6}$/i.test(value)) throw new Error(`${name}: ${value}`);
      colors[role as keyof EmailColors] = value.length === 4 ? expand(value) : value.toLowerCase();
    }
    return colors;
  };
  const root = resolveTheme(rules, { system: 'dark' });
  const get = (name: string) => {
    const v = root.get(name);
    if (v === undefined) throw new Error(`Missing ${name}`);
    return v;
  };
  const size = (step: string) => ({
    size: px(get(`--pk-font-size-${step}`)),
    line: px(get(`--pk-line-height-${step}`)),
  });
  return {
    light: scheme('light'),
    dark: scheme('dark'),
    font: { sans: get('--pk-font-sans').replaceAll('"', "'") },
    radius: {
      md: px(get('--pk-radius-md')),
      lg: px(get('--pk-radius-lg')),
      xl: px(get('--pk-radius-xl')),
    },
    text: { xs: size('xs'), sm: size('sm'), xl: size('xl'), '2xl': size('2xl') },
    weight: {
      medium: Number(get('--pk-font-weight-medium')),
      semibold: Number(get('--pk-font-weight-semibold')),
    },
    tracking: get('--pk-tracking-tight'),
  };
}

const expand = (hex: string) => `#${[...hex.slice(1)].map((c) => c + c).join('')}`.toLowerCase();

const literal = (value: unknown) =>
  JSON.stringify(value, null, 2).replace(/"([a-zA-Z]\w*)":/g, '$1:');

/** src/generated/resolved-tokens.ts: the email tokens and the SSR theme-color per scheme. */
export function resolvedTokensTs(sources: Sources): string {
  const email = emailTokens(sources);
  return `// Generated by tools/build-ssr-tokens.ts from the SPA's token sheets. Do not edit; run \`npm run gen\`.

/** The SPA tokens per theme, resolved for inline email styles; sizes in px. */
export const EMAIL_TOKENS = ${literal(email)} as const;

/** The page surface per scheme, for the SSR pages' theme-color meta. */
export const THEME_COLOR = ${literal({ light: email.light.page, dark: email.dark.page })} as const;
`;
}
