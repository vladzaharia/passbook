// Renders the capability matrix from the compilers' own declarations.

import { GOOGLE_TYPES } from '../../src/passkit/template/wallets/schema.ts';
import { googleCapabilities } from '../../src/passkit/wallets/google/capabilities.ts';
import { SAMSUNG_CAPABILITIES } from '../../src/passkit/wallets/samsung/capabilities.ts';
import {
  CAPABILITY_IDS,
  type CapabilityId,
  type Support,
} from '../../src/passkit/wallets/vocab.ts';

type Table = Record<CapabilityId, Support>;

export interface Column {
  target: 'google' | 'samsung';
  type: string;
  table: Table;
}

export function columns(): Column[] {
  return [
    ...GOOGLE_TYPES.map((type) => ({
      target: 'google' as const,
      type,
      table: googleCapabilities(type),
    })),
    ...(Object.entries(SAMSUNG_CAPABILITIES) as [string, Table][]).map(([type, table]) => ({
      target: 'samsung' as const,
      type,
      table,
    })),
  ];
}

export function renderModule(header: string): string {
  const cols = columns();
  const body = (target: Column['target']) =>
    cols
      .filter((c) => c.target === target)
      .map((c) => `    ${c.type}: ${JSON.stringify(c.table)},`)
      .join('\n');
  return `${header}import type { CapabilityId, Support } from '../passkit/wallets/vocab.ts';

type Table = Record<CapabilityId, Support>;

export const WALLET_CAPABILITIES = {
  google: {
${body('google')}
  },
  samsung: {
${body('samsung')}
  },
} as const satisfies Record<string, Record<string, Table>>;
`;
}

export function renderDoc(): string {
  const cols = columns();
  const head = ['Capability', ...cols.map((c) => `${c.target} ${c.type}`)];
  const rows = CAPABILITY_IDS.map((id) => [`\`${id}\``, ...cols.map((c) => c.table[id])]);
  const line = (cells: string[]) => `| ${cells.join(' | ')} |`;
  return `<!-- Generated by tools/gen-wallet-capabilities.ts from the compilers. Do not edit. -->
# Wallet capability matrix

Best case per capability, for a pass that uses it. A limit (a value too long, a full notice) can
only make a report item worse than the level here. Levels: \`native\` (own slot), \`text\` (carried
as a labelled line), \`difference\` (carried, looks different), \`omitted\` (left out and reported),
\`unsupported\` (the wallet has no such thing). Apple is the reference and carries all of it.

${line(head)}
${line(head.map(() => '---'))}
${rows.map(line).join('\n')}
`;
}
