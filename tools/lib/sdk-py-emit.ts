// Text of the generated Python files under sdk/python/src/passbook/_generated, from the operations in sdk-ts-ops.ts.
import { isPyKeyword, pascal, pyName } from '../../src/shared/sdk-names.ts';
import { type Decl, type Models, refsOf, type Ty } from './sdk-model.ts';
import type { SdkOp } from './sdk-ts-ops.ts';
import type { Schema } from './sdk-ts-schema.ts';

const HEADER = '# Generated by tools/gen-sdk-py.ts from docs/api/openapi.v1.json. Do not edit.\n';
const KEYWORDS = { has: isPyKeyword };
/** Attributes of pydantic's BaseModel that a field must not shadow. */
const SHADOW = new Set(
  'copy json dict construct validate schema schema_json parse_obj parse_raw parse_file from_orm update_forward_refs'.split(
    ' ',
  ),
);
const OPTION_NAMES = new Set(['headers', 'idempotency_key', 'max_retries', 'timeout', 'body']);

const lit = (v: string | number | boolean | null): string =>
  v === null ? 'None' : typeof v === 'boolean' ? (v ? 'True' : 'False') : JSON.stringify(v);

/**
 * The Python type of a Ty. With `open`, string enums also take any `str`: a newer API must not break
 * an older SDK.
 */
export function pyType(ty: Ty, prefix = '', open = false): string {
  switch (ty.k) {
    case 'str':
      return 'str';
    case 'int':
      return 'int';
    case 'num':
      return 'float';
    case 'bool':
      return 'bool';
    case 'null':
      return 'None';
    case 'any':
      return '_Any';
    case 'ref':
      return `${prefix}${ty.name}`;
    case 'lit':
      return `_Literal[${ty.values.map(lit).join(', ')}]${open && ty.values.every((v) => v === null || typeof v === 'string') ? ' | str' : ''}`;
    case 'list':
      return `_List[${pyType(ty.of, prefix, open)}]`;
    case 'map':
      return `_Dict[str, ${pyType(ty.of, prefix, open)}]`;
    case 'tuple':
      if (ty.rest)
        return ty.of.length === 0
          ? `_Tuple[${pyType(ty.rest, prefix, open)}, ...]`
          : '_Tuple[_Any, ...]';
      return `_Tuple[${ty.of.map((t) => pyType(t, prefix, open)).join(', ')}]`;
    case 'union':
      return ty.of.map((t) => pyType(t, prefix, open)).join(' | ');
  }
}

const nullable = (ty: Ty): boolean =>
  ty.k === 'null' ||
  (ty.k === 'union' && ty.of.some(nullable)) ||
  (ty.k === 'lit' && ty.values.includes(null));

function attribute(json: string, taken: Set<string>): { name: string; alias: boolean } {
  let name = json;
  const plain = /^[A-Za-z][A-Za-z0-9_]*$/.test(json) && !KEYWORDS.has(json);
  const ok = plain && !SHADOW.has(json) && !json.startsWith('model_');
  if (!ok) {
    name = json.replace(/[^A-Za-z0-9_]/g, '_').replace(/^(?=[0-9_])/, 'f_');
    name = `${name}_`;
  }
  while (taken.has(name)) name = `${name}_`;
  taken.add(name);
  return { name, alias: name !== json };
}

function classText(decl: Extract<Decl, { kind: 'object' }>): string {
  const taken = new Set<string>();
  const lines = decl.fields.map((f) => {
    const { name, alias } = attribute(f.json, taken);
    // A one-value `type` is the discriminator of an event; it stays strict so an unknown event falls through.
    const discriminator = f.json === 'type' && f.ty.k === 'lit' && f.ty.values.length === 1;
    const type = pyType(f.ty, '', !discriminator) + (f.required || nullable(f.ty) ? '' : ' | None');
    const optional = !f.required;
    if (alias) {
      const args = [...(optional ? ['default=None'] : []), `alias=${JSON.stringify(f.json)}`];
      return `    ${name}: ${type} = _Field(${args.join(', ')})`;
    }
    return `    ${name}: ${type}${optional ? ' = None' : ''}`;
  });
  return `class ${decl.name}(_Model):\n${lines.length ? lines.join('\n') : '    pass'}\n`;
}

/** Aliases in an order where each follows the aliases it names. */
function orderedAliases(aliases: Array<Extract<Decl, { kind: 'alias' }>>): typeof aliases {
  const byName = new Map(aliases.map((a) => [a.name, a]));
  const out: typeof aliases = [];
  const state = new Map<string, 'open' | 'done'>();
  const visit = (a: (typeof aliases)[number]) => {
    if (state.get(a.name) === 'done') return;
    if (state.get(a.name) === 'open') throw new Error(`Type alias ${a.name} refers to itself`);
    state.set(a.name, 'open');
    for (const ref of refsOf(a.ty)) {
      const next = byName.get(ref);
      if (next) visit(next);
    }
    state.set(a.name, 'done');
    out.push(a);
  };
  for (const a of aliases) visit(a);
  return out;
}

/** What verify_webhook returns when an event is newer than this SDK: any object, with the usual fields if present. */
const UNKNOWN_EVENT = `class UnknownWebhookEvent(_Model):
    """An event this SDK has no type for; the fields it does not name are kept as attributes."""

    id: str | None = None
    type: str | None = None
    apiVersion: str | None = None
    createdAt: int | None = None
    orgId: str | None = None
    mode: str | None = None
    data: _Dict[str, _Any] | None = None
`;

/** The webhook event union ends in UnknownWebhookEvent, tried last, so a newer event still parses. */
function aliasType(a: Extract<Decl, { kind: 'alias' }>): string {
  const text = pyType(a.ty, '', true);
  return a.name === 'WebhookEvent'
    ? `_Annotated[${text} | UnknownWebhookEvent, _Field(union_mode="left_to_right")]`
    : text;
}

export function modelsFile(models: Models): string {
  const decls = [...models.decls.values()].sort((a, b) => (a.name < b.name ? -1 : 1));
  const objects = decls.filter((d): d is Extract<Decl, { kind: 'object' }> => d.kind === 'object');
  const aliases = orderedAliases(
    decls.filter((d): d is Extract<Decl, { kind: 'alias' }> => d.kind === 'alias'),
  );
  const names = [...decls.map((d) => d.name), 'UnknownWebhookEvent'].sort();
  return [
    HEADER,
    'from __future__ import annotations\n',
    'from typing import Annotated as _Annotated, Any as _Any, Dict as _Dict, List as _List, Literal as _Literal, Tuple as _Tuple\n',
    'from pydantic import Field as _Field\n',
    'from .._model import Model as _Model\n',
    `__all__ = [\n${names.map((n) => `    ${JSON.stringify(n)},`).join('\n')}\n]\n`,
    ...objects.map(classText),
    UNKNOWN_EVENT,
    ...aliases.map((a) => `${a.name} = ${aliasType(a)}\n`),
  ].join('\n');
}

/** What the generator decided for one operation. */
export interface PyOp {
  op: SdkOp;
  body?: Ty;
  result?: Ty;
  item?: Ty;
  path: Array<{ name: string; py: string; ty: Ty }>;
  query: Array<{ name: string; py: string; ty: Ty; required: boolean }>;
}

function paramName(name: string, taken: Set<string>, what: string): string {
  const py = pyName(name);
  if (taken.has(py)) throw new Error(`${what}: parameter ${name} collides with ${py}`);
  taken.add(py);
  return py;
}

/** Declares each operation's body and result types, and works out its parameters. */
export function planOps(models: Models, ops: SdkOp[]): PyOp[] {
  return ops.map((op) => {
    const what = `${op.resource.join('.')}.${op.method}`;
    const taken = new Set(OPTION_NAMES);
    const path = op.schemas.path.map((p) => ({
      name: p.name,
      py: paramName(p.name, taken, what),
      ty: models.lower(p.schema, `${op.typeName}${pascal(p.name)}`),
    }));
    const query = op.schemas.query.map((q) => ({
      name: q.name,
      py: paramName(q.name, taken, what),
      ty: models.lower(q.schema, `${op.typeName}Query${pascal(q.name)}`),
      required: q.required,
    }));
    const body = op.schemas.body ? models.named(`${op.typeName}Body`, op.schemas.body) : undefined;
    const result = op.schemas.result
      ? models.named(`${op.typeName}Result`, op.schemas.result)
      : undefined;
    return {
      op,
      path,
      query,
      ...(body ? { body } : {}),
      ...(result ? { result } : {}),
      ...(op.cursor && op.schemas.result ? { item: itemType(models, op, op.schemas.result) } : {}),
    };
  });
}

/** The element type of a list's pages: `items` of the result, or of each variant of it. */
export function itemType(models: Models, op: SdkOp, result: Schema): Ty {
  const root = models.schemaOf(result);
  const pages = root.anyOf ?? [root];
  const items = pages.map((p, i) => {
    const schema = models.schemaOf(p).properties?.items;
    const hint = `${op.typeName}Item${pages.length > 1 ? i + 1 : ''}`;
    return models.lower(schema?.items ?? {}, hint);
  });
  const seen = new Set<string>();
  const unique = items.filter((t) => !seen.has(JSON.stringify(t)) && seen.add(JSON.stringify(t)));
  return unique.length === 1 ? (unique[0] as Ty) : { k: 'union', of: unique };
}

interface Node {
  path: string[];
  ops: PyOp[];
  children: Map<string, Node>;
}

export function resourceTree(ops: PyOp[]): Map<string, Node> {
  const roots = new Map<string, Node>();
  for (const p of ops) {
    let level = roots;
    let node: Node | undefined;
    p.op.resource.forEach((segment, i) => {
      node = level.get(segment);
      if (!node) {
        node = { path: p.op.resource.slice(0, i + 1), ops: [], children: new Map() };
        level.set(segment, node);
      }
      level = node.children;
    });
    node?.ops.push(p);
  }
  return roots;
}

const className = (path: string[]): string => `${pascal(path.join(' '))}Resource`;
const attr = pyName;

function methodText(p: PyOp): string {
  const { op } = p;
  const m = (ty: Ty) => pyType(ty, 'm.');
  const args = ['self', ...p.path.map((x) => `${x.py}: ${m(x.ty)}`)];
  const call: string[] = [`"${op.http}"`];
  const path = op.path.replace(/\{(\w+)\}/g, (_, n: string) => {
    const param = p.path.find((x) => x.name === n);
    return `{_p(${param?.py})}`;
  });
  call.push(p.path.length ? `f"${path}"` : `"${path}"`);
  if (p.body) {
    const required = op.body?.required === true;
    args.push(`body: ${m(p.body)} | _Dict[str, _Any]${required ? '' : ' | None = None'}`);
    call.push('body=body');
  } else if (op.binary) {
    args.push('body: bytes');
    call.push('body=body', `content_type="${op.binary}"`);
  }
  const keyword = [
    ...p.query.map((q) => `${q.py}: ${m(q.ty)}${q.required ? '' : ' | None = None'}`),
  ];
  // A required keyword argument may follow an optional one; Python allows it after `*`.
  args.push(...(keyword.length ? ['*', ...keyword] : []), '**opts: _Unpack[RequestOptions]');
  if (p.query.length)
    call.push(`query={${p.query.map((q) => `${JSON.stringify(q.name)}: ${q.py}`).join(', ')}}`);
  if (op.idempotent) call.push('idempotent=True');
  if (op.raw) call.push('raw=True');
  const returns = op.cursor
    ? `Page[${m(p.item as Ty)}]`
    : op.raw
      ? 'httpx.Response'
      : p.result
        ? m(p.result)
        : 'None';
  if (p.result && !op.raw) call.push(`result=${m(p.result)}`);
  const target = op.cursor
    ? `self._core.paginate(${[...call, `cursor_param="${op.cursor}"`, '**opts'].join(', ')})`
    : `self._core.request(${[...call, '**opts'].join(', ')})`;
  const doc = `${op.summary ? `${op.summary} ` : ''}\`${op.http} ${op.path}\``.replace(
    /"""/g,
    "'''",
  );
  return `    def ${attr(op.method)}(\n        ${args.join(',\n        ')},\n    ) -> ${returns}:\n        """${doc}"""\n        return ${target}\n`;
}

function classBody(node: Node): string {
  const children = [...node.children.entries()];
  const methodNames = new Set(node.ops.map((p) => attr(p.op.method)));
  for (const [name] of children)
    if (methodNames.has(attr(name)))
      throw new Error(`${className(node.path)}: child resource ${name} has the name of a method`);
  const inits = children.map(
    ([name, child]) => `        self.${attr(name)} = ${className(child.path)}(core)\n`,
  );
  const methods = node.ops.sort((a, b) => (a.op.method < b.op.method ? -1 : 1)).map(methodText);
  return [
    `class ${className(node.path)}:\n`,
    '    def __init__(self, core: Core) -> None:\n        self._core = core\n',
    ...inits,
    ...methods.map((t) => `\n${t}`),
  ].join('');
}

function* walk(node: Node): Generator<Node> {
  for (const child of node.children.values()) yield* walk(child);
  yield node;
}

export function resourcesFile(tree: Map<string, Node>): string {
  const classes = [...tree.values()].flatMap((root) => [...walk(root)]).map(classBody);
  const entries = [...tree.entries()];
  const root = [
    'class Resources:\n    """Every resource, named as in docs/api/sdk-names.json, in snake_case."""\n\n',
    '    def __init__(self, core: Core) -> None:\n',
    ...entries.map(
      ([name, node]) => `        self.${attr(name)} = ${className(node.path)}(core)\n`,
    ),
  ].join('');
  return [
    HEADER,
    'from __future__ import annotations\n',
    'from typing import Any as _Any, Dict as _Dict, List as _List, Literal as _Literal, Tuple as _Tuple\n',
    'import httpx\nfrom typing_extensions import Unpack as _Unpack\n',
    'from .._core import Core, RequestOptions, path_param as _p\nfrom .._pagination import Page\nfrom . import models as m\n',
    ...classes.map((c) => `\n${c}`),
    `\n${root}`,
  ].join('\n');
}
