// Text of the generated Go files in sdk/go, from the operations in sdk-ts-ops.ts. Output follows gofmt.
import { goName, pascal } from '../../src/shared/sdk-names.ts';
import type { Decl, Field, Models, Ty } from './sdk-model.ts';
import { itemType } from './sdk-py-emit.ts';
import type { SdkOp } from './sdk-ts-ops.ts';

const HEADER = '// Generated by tools/gen-sdk-go.ts from docs/api/openapi.v1.json. Do not edit.\n';
/** Exported names the hand-written files declare; a schema may not reuse one. */
export const RESERVED = new Set([
  'APIError',
  'Client',
  'ConnectionError',
  'Event',
  'Option',
  'Pager',
  'RequestOption',
  'Resources',
  'VerifyOption',
  'WebhookSignatureError',
]);
interface G {
  t: string;
  /** The Go type's zero value is nil, so it needs no pointer to be absent. */
  nilable: boolean;
}

export { goName };

export class GoTypes {
  private readonly models: Models;
  constructor(models: Models) {
    this.models = models;
  }

  /** JSON `null` is a legal value of the type, through any aliases. */
  nullable(ty: Ty, seen = new Set<string>()): boolean {
    switch (ty.k) {
      case 'null':
        return true;
      case 'lit':
        return ty.values.includes(null);
      case 'union':
        return ty.of.some((t) => this.nullable(t, seen));
      case 'ref': {
        const decl = this.models.decls.get(ty.name);
        if (decl?.kind !== 'alias' || seen.has(ty.name)) return false;
        return this.nullable(decl.ty, new Set([...seen, ty.name]));
      }
      default:
        return false;
    }
  }

  of(ty: Ty, seen = new Set<string>()): G {
    switch (ty.k) {
      case 'str':
        return { t: 'string', nilable: false };
      case 'int':
        return { t: 'int64', nilable: false };
      case 'num':
        return { t: 'float64', nilable: false };
      case 'bool':
        return { t: 'bool', nilable: false };
      case 'null':
      case 'any':
        return { t: 'any', nilable: true };
      case 'ref': {
        const decl = this.models.decls.get(ty.name);
        if (decl?.kind === 'alias') {
          if (seen.has(ty.name)) return { t: 'any', nilable: true };
          return { t: ty.name, nilable: this.of(decl.ty, new Set([...seen, ty.name])).nilable };
        }
        return { t: ty.name, nilable: false };
      }
      case 'lit': {
        const values = ty.values.filter((v) => v !== null);
        const kinds = new Set(values.map((v) => typeof v));
        if (kinds.size !== 1) return { t: 'any', nilable: true };
        if (kinds.has('string')) return { t: 'string', nilable: false };
        if (kinds.has('boolean')) return { t: 'bool', nilable: false };
        return values.every(Number.isInteger)
          ? { t: 'int64', nilable: false }
          : { t: 'float64', nilable: false };
      }
      case 'list':
        return { t: `[]${this.of(ty.of, seen).t}`, nilable: true };
      case 'map':
        return { t: `map[string]${this.of(ty.of, seen).t}`, nilable: true };
      case 'tuple':
        return { t: '[]any', nilable: true };
      case 'union': {
        const parts = ty.of.filter((t) => t.k !== 'null').map((t) => this.of(t, seen));
        if (parts.length === 1) return parts[0] as G;
        const kinds = new Set(parts.map((p) => p.t));
        if (kinds.size === 1) return parts[0] as G;
        if ([...kinds].every((k) => k === 'int64' || k === 'float64'))
          return { t: 'float64', nilable: false };
        return { t: 'any', nilable: true };
      }
    }
  }

  /** The Go type of a struct field or parameter that may be absent or null. */
  optional(ty: Ty): string {
    const g = this.of(ty);
    return g.nilable ? g.t : `*${g.t}`;
  }

  isStruct(ty: Ty): boolean {
    return this.models.resolve(ty)?.kind === 'object';
  }
}

function structText(decl: Extract<Decl, { kind: 'object' }>, types: GoTypes): string {
  const taken = new Set<string>();
  const rows = decl.fields.map((f: Field) => {
    let name = goName(f.json);
    for (let n = 2; taken.has(name); n++) name = `${goName(f.json)}${n}`;
    taken.add(name);
    const optional = !f.required || types.nullable(f.ty);
    const g = types.of(f.ty);
    const type = optional && !g.nilable ? `*${g.t}` : g.t;
    return [name, type, `\`json:"${f.json}${f.required ? '' : ',omitempty'}"\``];
  });
  if (rows.length === 0) return `type ${decl.name} struct{}\n`;
  const w0 = Math.max(...rows.map((r) => (r[0] as string).length));
  const w1 = Math.max(...rows.map((r) => (r[1] as string).length));
  const lines = rows.map(
    (r) => `\t${(r[0] as string).padEnd(w0)} ${(r[1] as string).padEnd(w1)} ${r[2]}`,
  );
  return `type ${decl.name} struct {\n${lines.join('\n')}\n}\n`;
}

export function typesFile(models: Models, types: GoTypes): string {
  const decls = [...models.decls.values()].sort((a, b) => (a.name < b.name ? -1 : 1));
  for (const d of decls)
    if (RESERVED.has(d.name)) throw new Error(`${d.name} is also a name in sdk/go`);
  const body = decls.map((d) =>
    d.kind === 'object' ? structText(d, types) : `type ${d.name} = ${types.of(d.ty).t}\n`,
  );
  return `${HEADER}\npackage passbook\n\n${body.join('\n')}`;
}

/** What the generator decided for one operation. */
export interface GoOp {
  op: SdkOp;
  body?: Ty;
  query?: Ty;
  result?: Ty;
  item?: Ty;
}

export function planOps(models: Models, ops: SdkOp[]): GoOp[] {
  return ops.map((op) => {
    const body = op.schemas.body ? models.named(`${op.typeName}Body`, op.schemas.body) : undefined;
    const query = op.schemas.query.length
      ? models.named(`${op.typeName}Query`, {
          type: 'object',
          properties: Object.fromEntries(op.schemas.query.map((q) => [q.name, q.schema])),
          required: op.schemas.query.filter((q) => q.required).map((q) => q.name),
        })
      : undefined;
    const paged = op.cursor !== undefined && op.schemas.result !== undefined;
    const result =
      op.schemas.result && !paged
        ? models.named(`${op.typeName}Result`, op.schemas.result)
        : undefined;
    return {
      op,
      ...(body ? { body } : {}),
      ...(query ? { query } : {}),
      ...(result ? { result } : {}),
      ...(paged ? { item: itemType(models, op, op.schemas.result as never) } : {}),
    };
  });
}

interface Node {
  path: string[];
  ops: GoOp[];
  children: Map<string, Node>;
}

export function resourceTree(ops: GoOp[]): Map<string, Node> {
  const roots = new Map<string, Node>();
  for (const p of ops) {
    let level = roots;
    let node: Node | undefined;
    p.op.resource.forEach((segment, i) => {
      node = level.get(segment);
      if (!node) {
        node = { path: p.op.resource.slice(0, i + 1), ops: [], children: new Map() };
        level.set(segment, node);
      }
      level = node.children;
    });
    node?.ops.push(p);
  }
  return roots;
}

const className = (path: string[]): string => `${pascal(path.join(' '))}Resource`;

/** The call's path as Go string concatenation: "/a/" + pathEscape(id) + "/b". */
function pathExpr(op: SdkOp): string {
  const parts: string[] = [];
  let rest = op.path;
  for (;;) {
    const m = /\{(\w+)\}/.exec(rest);
    if (!m) break;
    const before = rest.slice(0, m.index);
    if (before) parts.push(JSON.stringify(before));
    parts.push(`pathEscape(${paramName(m[1] as string)})`);
    rest = rest.slice(m.index + m[0].length);
  }
  if (rest) parts.push(JSON.stringify(rest));
  return parts.join(' + ');
}

const GO_KEYWORDS = new Set(
  'break case chan const continue default defer else fallthrough for func go goto if import interface map package range return select struct switch type var'.split(
    ' ',
  ),
);
const paramName = (name: string): string =>
  GO_KEYWORDS.has(name) || ['ctx', 'body', 'query', 'opts', 'r', 'out'].includes(name)
    ? `${name}_`
    : name;

/** The Go signature pieces of an operation, shared with the generated test. */
export function signature(p: GoOp, types: GoTypes) {
  const { op } = p;
  const params = p.op.schemas.path.map((x, i) => ({
    name: paramName(x.name),
    type: (op.pathParams[i]?.type ?? 'string') === 'number' ? 'int64' : 'string',
  }));
  // Bodies and queries are always pointers, so a call looks the same whatever the type underneath is.
  const bodyParam = p.body ? { type: `*${types.of(p.body).t}` } : undefined;
  const queryParam = p.query ? `*${types.of(p.query).t}` : undefined;
  return { params, bodyParam, queryParam };
}

function methodText(p: GoOp, className_: string, types: GoTypes): string {
  const { op } = p;
  const { params, bodyParam, queryParam } = signature(p, types);
  const args = ['ctx context.Context', ...params.map((x) => `${x.name} ${x.type}`)];
  if (bodyParam) args.push(`body ${bodyParam.type}`);
  if (op.binary) args.push('body []byte');
  if (queryParam) args.push(`query ${queryParam}`);
  args.push('opts ...RequestOption');
  const fields = [`method: "${op.http}"`, `path: ${pathExpr(op)}`];
  if (queryParam) fields.push('query: queryValues(query)');
  if (bodyParam) fields.push('body: body');
  if (op.binary) fields.push('raw: body', `contentType: "${op.binary}"`);
  if (op.idempotent) fields.push('idempotent: true');
  const call = `call{${fields.join(', ')}}`;
  const doc = `// ${goName(op.method)} ${op.summary ? `${op.summary} ` : ''}\`${op.http} ${op.path}\`\n`;
  const head = `${doc}func (r *${className_}) ${goName(op.method)}(${args.join(', ')})`;
  if (op.cursor && p.item)
    return `${head} *Pager[${types.of(p.item).t}] {\n\treturn newPager[${types.of(p.item).t}](r.c, ${call}, "${op.cursor}", opts)\n}\n`;
  if (op.raw)
    return `${head} (*http.Response, error) {\n\treturn r.c.download(ctx, ${call}, opts)\n}\n`;
  if (!p.result) return `${head} error {\n\treturn r.c.do(ctx, ${call}, nil, opts)\n}\n`;
  const g = types.of(p.result);
  const pointer = types.isStruct(p.result);
  const type = g.t;
  return pointer
    ? `${head} (*${type}, error) {\n\tvar out ${type}\n\tif err := r.c.do(ctx, ${call}, &out, opts); err != nil {\n\t\treturn nil, err\n\t}\n\treturn &out, nil\n}\n`
    : `${head} (${type}, error) {\n\tvar out ${type}\n\terr := r.c.do(ctx, ${call}, &out, opts)\n\treturn out, err\n}\n`;
}

function classText(node: Node, types: GoTypes): string {
  const children = [...node.children.entries()];
  const name = className(node.path);
  const fields = [
    ['c', '*core'],
    ...children.map(([n, child]) => [goName(n), `*${className(child.path)}`]),
  ];
  const w = Math.max(...fields.map((f) => (f[0] as string).length));
  const struct = `type ${name} struct {\n${fields.map((f) => `\t${(f[0] as string).padEnd(w)} ${f[1]}`).join('\n')}\n}\n`;
  const inits = [
    ['c', 'c'],
    ...children.map(([n, child]) => [goName(n), `new${className(child.path)}(c)`]),
  ];
  const initWidth = Math.max(...inits.map(([k]) => (k as string).length));
  const init = [
    `func new${name}(c *core) *${name} {`,
    `\treturn &${name}{`,
    ...inits.map(([k, v]) => `\t\t${`${k}:`.padEnd(initWidth + 1)} ${v},`),
    '\t}',
    '}\n',
  ].join('\n');
  const methods = node.ops
    .sort((a, b) => (a.op.method < b.op.method ? -1 : 1))
    .map((p) => methodText(p, name, types));
  return [struct, init, ...methods].join('\n');
}

function* walk(node: Node): Generator<Node> {
  for (const child of node.children.values()) yield* walk(child);
  yield node;
}

export function resourcesFile(tree: Map<string, Node>, types: GoTypes): string {
  const classes = [...tree.values()]
    .flatMap((root) => [...walk(root)])
    .map((n) => classText(n, types));
  const entries = [...tree.entries()];
  const w = Math.max(...entries.map(([n]) => goName(n).length));
  const root = [
    '// Resources are every resource, named as in docs/api/sdk-names.json.',
    'type Resources struct {',
    ...entries.map(([n, node]) => `\t${goName(n).padEnd(w)} *${className(node.path)}`),
    '}\n',
    'func newResources(c *core) Resources {',
    '\treturn Resources{',
    ...entries.map(
      ([n, node]) => `\t\t${`${goName(n)}:`.padEnd(w + 1)} new${className(node.path)}(c),`,
    ),
    '\t}',
    '}\n',
  ].join('\n');
  return `${HEADER}\npackage passbook\n\nimport (\n\t"context"\n\t"net/http"\n)\n\n${classes.join('\n')}\n${root}`;
}
