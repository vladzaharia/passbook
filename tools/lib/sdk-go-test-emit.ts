// The table of ops_gen_test.go: one row per operation with a request and a response made from the contract.
// The test runner is hand-written (sdk/go/ops_test.go); this file only says what to call.
import { type GoOp, type GoTypes, goName, signature } from './sdk-go-emit.ts';
import { sampleOf } from './sdk-sample.ts';
import type { Schema } from './sdk-ts-schema.ts';

const rowName = (path: string[], method: string): string => [...path, method].join('.');

function raw(value: unknown): string {
  const text = JSON.stringify(value);
  if (text.includes('`')) throw new Error('A sample contains a backtick');
  return `\`${text}\``;
}

export function testFile(plan: GoOp[], types: GoTypes, schemas: Record<string, Schema>): string {
  const rows = plan.map((p) => {
    const { op } = p;
    const { params, bodyParam } = signature(p, types);
    const values = params.map((x, i) => (x.type === 'int64' ? `int64(${i + 1})` : `"id${i + 1}"`));
    const path = op.path.replace(/\{(\w+)\}/g, (_, n: string) => {
      const i = op.schemas.path.findIndex((x) => x.name === n);
      return params[i]?.type === 'int64' ? String(i + 1) : `id${i + 1}`;
    });
    const target = ['c', ...op.resource.map(goName), goName(op.method)].join('.');
    const args = ['ctx', ...values];
    const prelude: string[] = [];
    const sample = op.schemas.body ? sampleOf(schemas, op.schemas.body) : undefined;
    if (p.body && bodyParam) {
      const g = types.of(p.body);
      prelude.push(
        `\t\t\tvar b ${g.t}`,
        '\t\t\tif err := json.Unmarshal(body, &b); err != nil {',
        '\t\t\t\treturn nil, err',
        '\t\t\t}',
      );
      args.push('&b');
    } else if (op.binary) args.push('body');
    if (p.query) args.push('nil');
    const call = `${target}(${args.join(', ')})`;
    const returns = op.cursor
      ? [`\t\t\treturn ${call}.All(ctx)`]
      : op.raw
        ? [`\t\t\treturn downloaded(${call})`]
        : p.result
          ? [`\t\t\treturn ${call}`]
          : [`\t\t\treturn nil, ${call}`];
    const result = op.schemas.result ? sampleOf(schemas, op.schemas.result) : undefined;
    const response =
      result === undefined
        ? '""'
        : raw(
            op.cursor && typeof result === 'object' && result !== null
              ? 'hasMore' in result
                ? { ...result, hasMore: false }
                : { ...result, nextCursor: null }
              : result,
          );
    const bodyText = sample === undefined ? '""' : raw(sample);
    const bodyArg = op.binary ? '"png"' : bodyText;
    return [
      '\t{',
      `\t\t${JSON.stringify(rowName(op.resource, op.method))}, "${op.http}", "${path}", ${op.idempotent},`,
      `\t\t${bodyArg}, ${response},`,
      `\t\tfunc(ctx context.Context, c *Client, ${p.body || op.binary ? 'body' : '_'} []byte) (any, error) {`,
      ...prelude,
      ...returns,
      '\t\t},',
      '\t},',
    ].join('\n');
  });
  const needsJson = rows.some((r) => r.includes('json.Unmarshal'));
  return `// Generated by tools/gen-sdk-go.ts from docs/api/openapi.v1.json. Do not edit.\n\npackage passbook\n\nimport (\n\t"context"\n${needsJson ? '\t"encoding/json"\n' : ''})\n\nvar generatedOps = []opCase{\n${rows.join('\n')}\n}\n`;
}
