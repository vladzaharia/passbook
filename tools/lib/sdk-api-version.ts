import { readFileSync } from 'node:fs';
import { resolve } from 'node:path';

/** The newest date in docs/api/versions.json: the `PassBook-Version` the SDKs send by default. */
export function newestApiVersion(): string {
  const file = resolve(import.meta.dirname, '../../docs/api/versions.json');
  const { versions } = JSON.parse(readFileSync(file, 'utf8')) as { versions: { date: string }[] };
  const dates = versions.map((v) => v.date).sort();
  const newest = dates.at(-1);
  if (!newest) throw new Error('docs/api/versions.json lists no version.');
  return newest;
}

const header = (c: string) =>
  `${c} Generated by tools/gen-sdk-*.ts from docs/api/versions.json. Do not edit.`;

export const tsApiVersionFile = (v: string) =>
  `${header('//')}\nexport const API_VERSION = '${v}';\n`;
export const pyApiVersionFile = (v: string) => `${header('#')}\nAPI_VERSION = "${v}"\n`;
export const goApiVersionFile = (v: string) =>
  `${header('//')}\n\npackage passbook\n\n// apiVersion is the default PassBook-Version.\nconst apiVersion = "${v}"\n`;
