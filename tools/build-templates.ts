// Codegen for src/generated/*. Run via `npm run gen`; CI fails if the output drifts.
import { existsSync, mkdirSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
import {
  type BehaviorRegistry,
  createBehaviorRegistry,
} from '../src/passkit/behaviors/registry.ts';
import type { BehaviorPlugin } from '../src/passkit/types.ts';
import { collectBaked, renderBakedModule } from './lib/baked-templates.ts';

const root = resolve(import.meta.dirname, '..');
const out = join(root, 'src/generated');
const HEADER = '// Generated by tools/build-templates.ts. Do not edit.\n';

function write(name: string, content: string): void {
  const file = join(out, name);
  mkdirSync(dirname(file), { recursive: true });
  if (existsSync(file) && readFileSync(file, 'utf8') === content) return;
  writeFileSync(file, content);
}

function dirs(path: string): string[] {
  if (!existsSync(path)) return [];
  return readdirSync(path)
    .filter((name) => statSync(join(path, name)).isDirectory())
    .sort();
}

function wwdr(): void {
  const pem = readFileSync(join(root, 'certificates/AppleWWDRCAG4.pem'), 'utf8').trim();
  write('wwdr-g4.ts', `${HEADER}export default ${JSON.stringify(`${pem}\n`)};\n`);
}

async function bakedTemplates(): Promise<void> {
  const behaviors = await loadBehaviors();
  const templates = await collectBaked({
    templatesDir: join(root, 'templates'),
    publicDir: join(root, 'public'),
    behaviors,
    log: (line) => console.warn(line),
  });
  write('baked-templates.ts', renderBakedModule(templates, HEADER));
  for (const t of templates) {
    const kb = (n: number) => `${Math.round(n / 1024)} KB`;
    const json = new TextEncoder().encode(JSON.stringify(t.passJson)).length;
    const total = t.assets.reduce((n, a) => n + a.size, json);
    const largest = t.assets.reduce((m, a) => (a.size > m.size ? a : m), { name: '-', size: 0 });
    console.log(
      `templates/${t.slug}: ${kb(total)} package, largest ${largest.name} ${kb(largest.size)}`,
    );
  }
}

async function loadBehaviors(): Promise<BehaviorRegistry> {
  const generated = (await import(pathToFileURL(join(out, 'behaviors.ts')).href)) as {
    behaviorPlugins: BehaviorPlugin[];
  };
  return createBehaviorRegistry(generated.behaviorPlugins);
}

function registry(options: {
  file: string;
  scanDir: string;
  importBase: string;
  typeImport: string;
  typeName: string;
  exportName: string;
}): void {
  const names = dirs(join(root, options.scanDir)).filter((name) =>
    existsSync(join(root, options.scanDir, name, 'index.ts')),
  );
  const idents = names.map((name) => name.replace(/-([a-z])/g, (_, c: string) => c.toUpperCase()));
  const imports = names.map(
    (name, i) => `import ${idents[i]} from '${options.importBase}/${name}/index.ts';`,
  );
  write(
    options.file,
    `${HEADER}${options.typeImport}\n${imports.join('\n')}${imports.length ? '\n' : ''}
export const ${options.exportName}: readonly ${options.typeName}[] = [${idents.join(', ')}];
`,
  );
}

