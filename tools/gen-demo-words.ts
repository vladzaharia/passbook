// Writes src/generated/demo-words.ts from faker's locale data. Run via `npm run gen:demo-words`, on purpose:
// the Worker ships only these lists, never faker, so a faker bump changes nothing until this runs and the
// golden tests show the difference.
import { writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { allFakers } from '@faker-js/faker';

const LOCALES = [
  ['en-US', 'en'],
  ['en-GB', 'en_GB'],
  ['de-DE', 'de'],
  ['fr-FR', 'fr'],
  ['es-ES', 'es'],
] as const;

type Fk = (typeof allFakers)['en'];
type Defs = Record<string, Record<string, unknown> | undefined>;

function defs(f: Fk, mod: string, key: string): unknown {
  try {
    return (f.definitions as unknown as Defs)[mod]?.[key];
  } catch {
    return undefined;
  }
}

/** Every string in a list or in a { generic, female, male } record, in faker's order, no repeats. */
function strings(value: unknown): string[] {
  const parts = Array.isArray(value)
    ? value
    : value && typeof value === 'object'
      ? Object.values(value).flat()
      : [];
  return [...new Set(parts.filter((x): x is string => typeof x === 'string'))];
}

/** Evenly spaced picks, so a short list still covers the whole alphabet. */
function pick(list: string[], max: number): string[] {
  if (list.length <= max) return list;
  return Array.from({ length: max }, (_, i) => list[Math.floor((i * list.length) / max)] as string);
}

const plain = (w: string) =>
  /^\p{L}+$/u.test(w) && w !== w.toUpperCase() && w.length >= 4 && w.length <= 10;
const name = (w: string) => /^[\p{L}][\p{L}'-]*$/u.test(w) && w.length <= 14;

// faker falls back to English for these in de and es; real street words go here instead.
const STREET: Record<string, string[]> = {
  'de-DE': ['straße', 'weg', 'allee', 'platz', 'gasse', 'ring'],
  'es-ES': ['Mayor', 'Nueva', 'Real', 'del Sol', 'de la Paz', 'del Mar', 'Alta', 'Ancha'],
};

function wordsFor(locale: string, key: string) {
  const f = allFakers[key as keyof typeof allFakers] as Fk;
  const en = allFakers.en;
  const pool = (mod: string, k: string) => {
    const list = strings(defs(f, mod, k));
    return list.length ? list : strings(defs(en, mod, k));
  };
  const postcodes = pool('location', 'postcode').filter((p) => !p.includes('-'));
  return {
    first: pick(pool('person', 'first_name').filter(name), 250),
    last: pick(pool('person', 'last_name').filter(name), 250),
    city: pick(pool('location', 'city_name').filter(name), 100),
    region: pool('location', 'state'),
    street: STREET[locale] ?? pick(pool('location', 'street_suffix'), 40),
    postcode: pick(postcodes, 12),
    adjective: pick(pool('word', 'adjective').filter(plain), 100),
    noun: pick(pool('word', 'noun').filter(plain), 100),
  };
}

const lines: string[] = [
  '// Generated by tools/gen-demo-words.ts from @faker-js/faker 10.6.0. Do not edit.',
  '// Run `npm run gen:demo-words` on purpose; the Worker ships these lists and never faker.',
  '',
  'export interface DemoWords {',
  '  first: readonly string[];',
  '  last: readonly string[];',
  '  city: readonly string[];',
  '  region: readonly string[];',
  '  street: readonly string[];',
  '  postcode: readonly string[];',
  '  adjective: readonly string[];',
  '  noun: readonly string[];',
  '}',
  '',
];
const seen = new Map<string, string>();
const entries: string[] = [];
for (const [locale, key] of LOCALES) {
  const words = wordsFor(locale, key);
  const fields = Object.entries(words).map(([field, list]) => {
    const json = JSON.stringify(list);
    const known = seen.get(json);
    if (known) return `    ${field}: ${known},`;
    const id = `${key}_${field}`;
    seen.set(json, id);
    lines.push(`const ${id}: readonly string[] = ${json};`);
    return `    ${field}: ${id},`;
  });
  entries.push(`  '${locale}': {\n${fields.join('\n')}\n  },`);
}
lines.push(
  '',
  "export const DEMO_LOCALES = ['en-US', 'en-GB', 'de-DE', 'fr-FR', 'es-ES'] as const;",
);
lines.push('', 'export const DEMO_WORDS: Record<(typeof DEMO_LOCALES)[number], DemoWords> = {');
lines.push(...entries, '};', '');

writeFileSync(resolve(import.meta.dirname, '../src/generated/demo-words.ts'), lines.join('\n'));
