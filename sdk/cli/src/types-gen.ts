/** JSON Schema (the subset template inputs use) to TypeScript type text. */
type Schema = Record<string, unknown>;

const IDENT = /^[A-Za-z_$][A-Za-z0-9_$]*$/;
const key = (name: string): string => (IDENT.test(name) ? name : JSON.stringify(name));
const pad = (depth: number): string => '  '.repeat(depth);
const isSchema = (v: unknown): v is Schema =>
  typeof v === 'object' && v !== null && !Array.isArray(v);
const list = (v: unknown): Schema[] => (Array.isArray(v) ? v.filter(isSchema) : []);
const union = (parts: string[]): string => [...new Set(parts)].join(' | ');
const comment = (text: string, depth: number): string =>
  `${pad(depth)}/** ${text.replaceAll('*/', '* /')} */\n`;

class Converter {
  private readonly root: Schema;
  constructor(root: Schema) {
    this.root = root;
  }

  private deref(ref: string): Schema {
    if (!ref.startsWith('#/')) throw new Error(`Only local $ref is supported, got ${ref}`);
    let cur: unknown = this.root;
    for (const part of ref.slice(2).split('/'))
      cur = isSchema(cur)
        ? cur[decodeURIComponent(part.replaceAll('~1', '/').replaceAll('~0', '~'))]
        : undefined;
    if (!isSchema(cur)) throw new Error(`${ref} does not resolve`);
    return cur;
  }

  type(s: Schema, depth: number, seen: string[] = []): string {
    if (typeof s.$ref === 'string') {
      if (seen.includes(s.$ref)) return 'unknown';
      return this.type(this.deref(s.$ref), depth, [...seen, s.$ref]);
    }
    if ('const' in s) return JSON.stringify(s.const);
    if (Array.isArray(s.enum)) return union(s.enum.map((v) => JSON.stringify(v)));
    const alternatives = list(s.anyOf).length ? list(s.anyOf) : list(s.oneOf);
    if (alternatives.length) return union(alternatives.map((a) => this.type(a, depth, seen)));
    if (list(s.allOf).length)
      return list(s.allOf)
        .map((a) => `(${this.type(a, depth, seen)})`)
        .join(' & ');
    const types = Array.isArray(s.type) ? s.type : typeof s.type === 'string' ? [s.type] : [];
    if (types.length === 0) return s.properties ? this.object(s, depth, seen) : 'unknown';
    return union(types.map((t) => this.single(String(t), s, depth, seen)));
  }

  private single(type: string, s: Schema, depth: number, seen: string[]): string {
    switch (type) {
      case 'string':
        return 'string';
      case 'integer':
      case 'number':
        return 'number';
      case 'boolean':
        return 'boolean';
      case 'null':
        return 'null';
      case 'array': {
        if (Array.isArray(s.prefixItems))
          return `[${list(s.prefixItems)
            .map((p) => this.type(p, depth, seen))
            .join(', ')}]`;
        return `Array<${isSchema(s.items) ? this.type(s.items, depth, seen) : 'unknown'}>`;
      }
      case 'object':
        return this.object(s, depth, seen);
      default:
        throw new Error(`Unsupported schema type "${type}"`);
    }
  }

  private object(s: Schema, depth: number, seen: string[]): string {
    const props = isSchema(s.properties) ? Object.entries(s.properties) : [];
    const extra = s.additionalProperties;
    const typedExtra = isSchema(extra) && Object.keys(extra).length > 0 ? extra : undefined;
    const open = extra === true || (isSchema(extra) && Object.keys(extra).length === 0);
    if (props.length === 0)
      return typedExtra || open
        ? `Record<string, ${typedExtra ? this.type(typedExtra, depth, seen) : 'unknown'}>`
        : '{}';
    const required = new Set(Array.isArray(s.required) ? s.required.map(String) : []);
    const lines = props.map(([name, schema]) => {
      const p = isSchema(schema) ? schema : {};
      const doc = [p['x-label'], p['x-help'], p.description].filter(
        (x): x is string => typeof x === 'string',
      );
      const note =
        typeof p.default !== 'undefined' ? [`Default ${JSON.stringify(p.default)}.`] : [];
      const text = [...doc, ...note].join(' ');
      return `${text ? comment(text, depth + 1) : ''}${pad(depth + 1)}${key(name)}${required.has(name) ? '' : '?'}: ${this.type(p, depth + 1, seen)};`;
    });
    if (open) lines.push(`${pad(depth + 1)}[key: string]: unknown;`);
    const body = `{\n${lines.join('\n')}\n${pad(depth)}}`;
    return typedExtra ? `${body} & Record<string, ${this.type(typedExtra, depth, seen)}>` : body;
  }
}

/** `Event ticket` -> `EventTicket`. */
export const typeName = (text: string): string => {
  const name = text
    .replace(/(^|[^A-Za-z0-9]+)([A-Za-z0-9])/g, (_, __, c: string) => c.toUpperCase())
    .replace(/[^A-Za-z0-9]/g, '');
  return /^[A-Za-z]/.test(name) ? name : `Template${name}`;
};

/** A module that exports `name`, the type of a template's `input`. */
export function inputTypeFile(
  schema: Schema,
  name: string,
  origin: { templateId: string; template: string },
): string {
  const header = `// Generated by \`passbook types ${origin.templateId}\`. Regenerate it when the template changes.\n`;
  const doc = `Input of \`passes.create\` for the template "${origin.template.replaceAll('*/', '* /')}".`;
  return `${header}\n/** ${doc} */\nexport type ${name} = ${new Converter(schema).type(schema, 0)};\n`;
}
