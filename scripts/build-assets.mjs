import { readdir, readFile, mkdir, writeFile, copyFile, rm } from 'node:fs/promises';
import {build} from 'esbuild';
// Artwork is baked into the deployment as private Worker Static Assets, keeping the JS bundle small.
// Preserve the supplied PNGs byte for byte. The Worker exposes only selected public brand images.
await mkdir('src/generated',{recursive:true});
await mkdir('public/admin',{recursive:true});
await build({entryPoints:['src/admin/client.ts'],outfile:'public/admin/studio.js',bundle:true,format:'esm',platform:'browser',target:['es2022'],minify:true,tsconfig:'tsconfig.admin.json'});
await copyFile('src/admin/studio.css','public/admin/studio.css');
await mkdir('public/apple',{recursive:true});
for(const name of ['add-to-apple-wallet.svg','add-to-apple-wallet.png'])await copyFile('assets/apple/'+name,'public/apple/'+name);
await writeFile('src/generated/wwdr-g4.ts','// Public Apple WWDR intermediate; generated by npm run assets.\nexport default '+JSON.stringify(await readFile('certificates/AppleWWDRCAG4.pem','utf8'))+';\n');
for(const bundle of (await readdir('templates')).filter(name=>/^[a-z0-9-]+\.pkpasstemplate$/.test(name))) {
 const slug=bundle.replace(/\.pkpasstemplate$/,'');
 const dir=`templates/${slug}.pkpasstemplate`;
 const names=(await readdir(dir,{recursive:true})).filter(n=>/\.(png|strings)$/.test(n) && !n.split('/').some(part=>part.startsWith('.'))).sort();
 await rm(`public/templates/${slug}`,{recursive:true,force:true});
 await mkdir(`public/templates/${slug}`,{recursive:true});
 for(const name of names) {
   if(name.includes('/')) await mkdir(`public/templates/${slug}/${name.slice(0,name.lastIndexOf('/'))}`,{recursive:true});
   await copyFile(`${dir}/${name}`,`public/templates/${slug}/${name}`);
 }
 await writeFile(`src/generated/${slug}-assets.ts`,'// Generated by npm run assets.\nexport default '+JSON.stringify(Object.fromEntries(names.map(n=>[n,`/templates/${slug}/${n}`])),null,2)+';\n');
 console.log(`${slug}: indexed ${names.length} original pass assets.`);
}
